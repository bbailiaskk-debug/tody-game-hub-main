import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const WRANGLER_CONFIG_PATH = new URL("../wrangler.json", import.meta.url);
const DEFAULT_OUT = fileURLToPath(new URL("../.env.kv", import.meta.url));

const ARGUMENTS = process.argv.slice(2);

function readOption(name) {
  const index = ARGUMENTS.indexOf(`--${name}`);
  return index >= 0 ? ARGUMENTS[index + 1] : undefined;
}

const usage =
  "Usage: node scripts/dump-kv.mjs [--binding AUTH_USERS_KV | --namespace-id <id>] [--out .env.kv]";

const require = createRequire(import.meta.url);

// Run wrangler's own entry point through this node binary rather than through npx: `npx` is a
// .cmd shim, which on Windows means spawning through cmd.exe, and handing an argument vector to a
// shell is how a KV key containing `&` becomes command injection.
const WRANGLER_BIN = fileURLToPath(
  new URL(
    `../node_modules/wrangler/${require("wrangler/package.json").bin.wrangler.slice(2)}`,
    import.meta.url,
  ),
);

function wrangler(args) {
  // A single KV value can be a whole auth-store blob, well past spawnSync's 1 MiB default.
  const result = spawnSync(process.execPath, [WRANGLER_BIN, ...args], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error((result.stderr || result.stdout || "").trim().slice(0, 400));
  }
  return result.stdout;
}

// Shush reads an env file with /^(\s*(?:export\s+)?[\w.-]+)(\s*=\s*)(.*)$/, and a line that does not
// match is dropped from the editor with no row and nothing masked. KV keys are full of `:` and `@`,
// and JSON paths reach arbitrary characters, so both are rewritten to `[A-Za-z0-9_.-]`.
function sanitize(segment) {
  let out = segment.replace(/[^A-Za-z0-9_.-]/g, (char) => {
    if (char === ":") return "__";
    if (char === "@") return "_at_";
    return "_";
  });
  if (out.length === 0) out = "_";
  if (!/^[A-Za-z_]/.test(out)) out = `_${out}`;
  return out;
}

// A value written verbatim into a single line, so an embedded newline would parse as extra rows.
// Same reason Shush collapses newlines when it writes a value back.
const MAX_VALUE_LENGTH = 400;

function flatten(value) {
  const collapsed = value.replace(/\s*[\r\n]+\s*/g, " ").trim();
  // Chat images and avatars are stored as base64 data URLs, and one of them is 787 KB. Masking a
  // blob of base64 hides nothing and leaves the editor with megabytes to render, so the size is
  // recorded instead. No secret here is that long; the longest real one is a refresh token.
  if (collapsed.length > MAX_VALUE_LENGTH) {
    return `<${collapsed.length} chars elided>`;
  }
  return collapsed;
}

function resolveNamespaceId() {
  const explicit = readOption("namespace-id");
  if (explicit) return explicit;
  const binding = readOption("binding") ?? "AUTH_USERS_KV";
  const config = JSON.parse(readFileSync(WRANGLER_CONFIG_PATH, "utf8"));
  const entry = (config.kv_namespaces ?? []).find((namespace) => namespace.binding === binding);
  if (!entry) throw new Error(`No kv_namespaces entry for binding "${binding}" in wrangler.json`);
  return entry.id;
}

// `auth-store` is one KV entry holding every user, and it is over a megabyte of JSON. Left as a
// single masked value it would be one unreadable row, so a JSON value is walked and each leaf
// becomes its own row - the same shape Shush's JSON mode shows, and the reason a row per secret is
// worth having at all.
function leafRows(value, prefix, rows) {
  let parsed;
  try {
    parsed = JSON.parse(value);
  } catch {
    return;
  }
  const walk = (node, path) => {
    if (node === null || typeof node !== "object") {
      rows.push([path.join("__"), flatten(typeof node === "string" ? node : JSON.stringify(node))]);
      return;
    }
    const entries = Array.isArray(node)
      ? node.map((item, index) => [String(index), item])
      : Object.entries(node);
    if (entries.length === 0) {
      rows.push([path.join("__"), flatten(JSON.stringify(node))]);
    }
    for (const [key, child] of entries) walk(child, [...path, sanitize(key)]);
  };
  walk(parsed, [prefix]);
  return rows.length > 0;
}

const namespaceId = resolveNamespaceId();
const outPath = readOption("out") ?? DEFAULT_OUT;

const listed = JSON.parse(
  wrangler(["kv", "key", "list", "--namespace-id", namespaceId, "--remote"]),
);
const names = listed.map((entry) => entry.name).sort();
if (names.length === 0) {
  console.error(`${usage}\n\nNamespace ${namespaceId} is empty.`);
  process.exit(1);
}

const taken = new Set();
const lines = [
  `# Cloudflare KV dump - namespace ${namespaceId}`,
  "# Generated by scripts/dump-kv.mjs. Plaintext: session tokens, refresh tokens and password",
  "# hashes. Never commit this file. Each `# was:` comment is the real KV key for the rows below.",
  "",
];

let rowCount = 0;

for (const name of names) {
  const value = wrangler(["kv", "key", "get", name, "--namespace-id", namespaceId, "--remote"]);
  const prefix = sanitize(name);
  const rows = [];

  if (!leafRows(value, prefix, rows)) {
    rows.push([prefix, flatten(value)]);
  }

  lines.push(`# was: ${name}`);
  for (const [key, rowValue] of rows) {
    let unique = key;
    let suffix = 2;
    while (taken.has(unique)) unique = `${key}_${suffix++}`;
    taken.add(unique);
    lines.push(`${unique}=${rowValue}`);
    rowCount += 1;
  }
  lines.push("");
}

writeFileSync(outPath, `${lines.join("\n")}\n`, "utf8");

console.log(`Wrote ${names.length} keys as ${rowCount} rows to ${outPath}`);
console.log("Open it in VS Code - Shush masks every value. Delete it when you're done.");
